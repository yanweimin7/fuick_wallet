const generateCoins = (count: number): CryptoTicker[] => {
  const coins: CryptoTicker[] = [];
  const symbolCount = CRYPTO_SYMBOLS.length;
  const nameCount = CRYPTO_NAMES_EN.length;

  for (let i = 0; i < count; i++) {
    const symbol = CRYPTO_SYMBOLS[i % symbolCount];
    const suffix = i < symbolCount ? "" : String(Math.floor(i / symbolCount));
    const fullSymbol = suffix ? `${symbol}${suffix}USDT` : `${symbol}USDT`;
    const price =
      symbol === "BTC"
        ? 67500
        : symbol === "ETH"
          ? 3450
          : symbol === "BNB"
            ? 605
            : symbol === "SOL"
              ? 172
              : symbol === "XRP"
                ? 0.52
                : symbol === "ADA"
                  ? 0.45
                  : symbol === "DOGE"
                    ? 0.125
                    : symbol === "DOT"
                      ? 7.2
                      : 0.0001 + Math.random() * 1000;

    const change24h = -15 + Math.random() * 30;
    const basePrice = price * (1 + change24h / 100);

    coins.push({
      symbol: fullSymbol,
      name: CRYPTO_NAMES_EN[i % nameCount],
      price: Number(price.toFixed(price < 1 ? 6 : price < 100 ? 4 : 2)),
      change24h: Number(change24h.toFixed(2)),
      volume24h: Math.floor(Math.random() * 50000000000) + 1000000,
      high24h: Number((basePrice * 1.05).toFixed(6)),
      low24h: Number((basePrice * 0.95).toFixed(6)),
    });
  }
  return coins;
};

const FALLBACK_DATA: CryptoTicker[] = generateCoins(550);

export class MarketService {
  static async getTopCoins(limit: number = 100): Promise<CryptoTicker[]> {
    return FALLBACK_DATA.slice(0, limit);
  }

  static async getCoinPrice(symbol: string): Promise<CryptoTicker | null> {
    return (
      FALLBACK_DATA.find(
        (t) => t.symbol.toUpperCase() === symbol.toUpperCase(),
      ) || null
    );
  }
}
